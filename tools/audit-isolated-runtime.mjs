import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { isolationPaths, validateIsolatedPaths, assertPhysicalIsolationBoundary } from "../apps/api/src/subscription-isolation.mjs";
import { validateAuthConfiguration } from "../apps/api/src/subscription-auth.mjs";
import { inspectIsolatedPlugin } from "../apps/api/src/isolated-plugin-evidence.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = isolationPaths(root);
process.env.OPENCLAW_STATE_DIR = target.state;
process.env.OPENCLAW_CONFIG_PATH = target.config;
process.env.OPENCLAW_LOAD_SHELL_ENV = "0";
process.env.OPENCLAW_SKIP_CRON = "1";
delete process.env.OPENCLAW_AGENT_DIR;
await assertPhysicalIsolationBoundary(root, target.state);
const config = JSON.parse(await fs.readFile(target.config, "utf8"));
validateIsolatedPaths(config, root);
validateAuthConfiguration(config);
await inspectIsolatedPlugin(root, process.env);
const dist = path.join(process.env.APPDATA, "npm", "node_modules", "openclaw", "dist");
const load = (file) => import(pathToFileURL(path.join(dist, file)));
const { r: validateCore } = await load("validation-core-C5ZDhifM.mjs");
const { a: validatePlugins } = await load("io.snapshot-preparation-B6fMdY05.mjs");
const { i: readRecords } = await load("installed-plugin-index-record-reader-B3UvF50J.mjs");
const { t: discover } = await load("io.plugin-metadata-C3hrpt6-.mjs");
const records = readRecords({ env: process.env, artifactPreservingReadOnly: true });
const record = records.codex;
if (!record?.installPath || !path.isAbsolute(record.installPath)) throw new Error("Isolated native Codex install record missing");
await assertPhysicalIsolationBoundary(target.state, record.installPath);
const pkg = JSON.parse(await fs.readFile(path.join(record.installPath, "package.json"), "utf8"));
if (pkg.name !== "@openclaw/codex" || pkg.version !== "2026.9.6") throw new Error("Native Codex package revision differs");
const registry = discover({ config, env: process.env, artifactPreservingReadOnly: true });
const core = validateCore(config);
const full = validatePlugins(config, { env: process.env, pluginValidation: "full", pluginMetadataSnapshot: { manifestRegistry: registry } });
if (!core.ok || !full.ok) throw new Error("Native isolated configuration validation failed");
const unsafeWarnings = (full.warnings || []).filter((warning) => /codex|plugin/i.test(JSON.stringify(warning)));
if (unsafeWarnings.length) throw new Error("Native plugin validation is incomplete; preserve staged data for review");
console.log(JSON.stringify({ status: "native-schema-verified", package: pkg.name, version: pkg.version, port: target.port, gatewayStarted: false }));
